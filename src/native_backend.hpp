// The first native backend uses the host's C++20 toolchain. This keeps C÷
// dependency-light while producing real native executables.
class NativeBackend {
public:
    explicit NativeBackend(const std::vector<Token>& tokens) : tokens_(tokens) {}

    std::string generate() {
        scopes_.emplace_back();
        while (!check(Kind::End)) {
            if (match(Kind::KwImport)) {
                parse_import();
            } else if (match(Kind::KwFn)) {
                functions_.push_back(parse_function());
            } else {
                main_body_ += parse_statement();
            }
        }

        std::ostringstream output;
        output << "// Generated by the C÷ native backend. Do not edit.\n"
               << "#include <cmath>\n#include <cstdint>\n#include <iostream>\n#include <string>\n\n";
        if (uses_math_) output << "using namespace std;\n\n";
        for (const auto& function : functions_) output << function << "\n";
        output << "int main() {\n" << main_body_ << "    return 0;\n}\n";
        return output.str();
    }

private:
    const std::vector<Token>& tokens_;
    std::size_t current_ = 0;
    int repeat_id_ = 0;
    int function_depth_ = 0;
    bool uses_math_ = false;
    std::vector<std::set<std::string>> scopes_;
    std::vector<std::string> functions_;
    std::string main_body_;

    const Token& peek() const { return tokens_.at(current_); }
    bool check(Kind kind) const { return peek().kind == kind; }
    bool at_end() const { return check(Kind::End); }
    const Token& advance() { if (!at_end()) ++current_; return tokens_.at(current_ - 1); }
    bool match(Kind kind) { if (!check(kind)) return false; advance(); return true; }

    [[noreturn]] void fail(const Token& token, const std::string& message) const {
        throw std::runtime_error("native backend: " + std::to_string(token.line) + ":" +
                                 std::to_string(token.column) + ": " + message);
    }

    const Token& consume(Kind kind, const std::string& message) {
        if (check(kind)) return advance();
        fail(peek(), message);
    }

    void declare_name(const std::string& name) { scopes_.back().insert(name); }

    bool is_declared(const std::string& name) const {
        for (auto scope = scopes_.rbegin(); scope != scopes_.rend(); ++scope) {
            if (scope->contains(name)) return true;
        }
        return false;
    }

    static std::string cpp_type(const Token& token, bool allow_void = false) {
        const auto& type = token.lexeme;
        if (type == "int") return "long long";
        if (type == "float" || type == "double") return "double";
        if (type == "bool") return "bool";
        if (type == "string" || type == "str") return "std::string";
        if (allow_void && type == "void") return "void";
        throw std::runtime_error("native backend: " + std::to_string(token.line) + ":" +
                                 std::to_string(token.column) +
                                 ": unknown or unsupported type '" + type + "'");
    }

    static std::string render(const std::vector<Token>& expression) {
        std::ostringstream out;
        bool first = true;
        for (const auto& token : expression) {
            if (!first) out << ' ';
            out << token.lexeme;
            first = false;
        }
        return out.str();
    }

    std::vector<Token> collect_until(Kind terminator) {
        std::vector<Token> expression;
        int parens = 0;
        while (!at_end()) {
            if (parens == 0 && check(terminator)) break;
            const Token token = advance();
            if (token.kind == Kind::LParen) ++parens;
            if (token.kind == Kind::RParen) {
                if (parens == 0) fail(token, "unmatched ')' in expression");
                --parens;
            }
            expression.push_back(token);
        }
        if (parens != 0) fail(peek(), "unclosed '(' in expression");
        if (expression.empty()) fail(peek(), "expected an expression");
        return expression;
    }

    std::vector<Token> collect_parenthesized() {
        std::vector<Token> expression;
        int parens = 0;
        while (!at_end()) {
            if (check(Kind::RParen) && parens == 0) break;
            const Token token = advance();
            if (token.kind == Kind::LParen) ++parens;
            if (token.kind == Kind::RParen) --parens;
            expression.push_back(token);
        }
        if (at_end()) fail(peek(), "expected ')' after expression");
        if (expression.empty()) fail(peek(), "expected an expression");
        consume(Kind::RParen, "expected ')' after expression");
        return expression;
    }

    void parse_import() {
        const Token& module = consume(Kind::Identifier, "expected a module name after 'import'");
        if (module.lexeme == "math") uses_math_ = true;
        else fail(module, "module '" + module.lexeme + "' is not available in this version");
        consume(Kind::Semicolon, "expected ';' after import");
    }

    std::string parse_function() {
        const Token& name = consume(Kind::Identifier, "expected a function name after 'fn'");
        consume(Kind::LParen, "expected '(' after function name");
        std::vector<std::string> parameters;
        std::vector<std::string> parameter_names;
        if (!check(Kind::RParen)) {
            do {
                const Token& parameter = consume(Kind::Identifier, "expected a parameter name");
                consume(Kind::Colon, "expected ':' after parameter name");
                const Token& type = consume(Kind::Identifier, "expected a parameter type");
                parameters.push_back(cpp_type(type) + " " + parameter.lexeme);
                parameter_names.push_back(parameter.lexeme);
            } while (match(Kind::Comma));
        }
        consume(Kind::RParen, "expected ')' after function parameters");

        std::string return_type = "auto";
        if (match(Kind::Arrow)) {
            const Token& type = consume(Kind::Identifier, "expected a return type after '->'");
            return_type = cpp_type(type, true);
        }

        std::ostringstream signature;
        signature << return_type << ' ' << name.lexeme << '(';
        for (std::size_t i = 0; i < parameters.size(); ++i) {
            if (i) signature << ", ";
            signature << parameters[i];
        }
        signature << ") ";

        scopes_.emplace_back();
        for (const auto& parameter : parameter_names) declare_name(parameter);
        ++function_depth_;
        const std::string body = parse_block();
        --function_depth_;
        scopes_.pop_back();
        return signature.str() + body;
    }

    std::string parse_block() {
        consume(Kind::LBrace, "expected '{' to start a block");
        scopes_.emplace_back();
        std::string body = "{\n";
        while (!check(Kind::RBrace) && !at_end()) {
            if (check(Kind::KwFn)) fail(peek(), "function declarations must be at the top level");
            body += parse_statement();
        }
        consume(Kind::RBrace, "expected '}' after block");
        scopes_.pop_back();
        body += "}\n";
        return body;
    }

    std::string parse_if() {
        const auto condition = render(collect_until(Kind::LBrace));
        std::string result = "if (" + condition + ") " + parse_block();
        if (match(Kind::KwElse)) {
            if (match(Kind::KwIf)) result += "else " + parse_if();
            else result += "else " + parse_block();
        }
        return result;
    }

    std::string parse_statement() {
        if (match(Kind::KwPrint)) {
            consume(Kind::LParen, "expected '(' after 'print'");
            const auto expression = render(collect_parenthesized());
            consume(Kind::Semicolon, "expected ';' after print statement");
            return "    std::cout << (" + expression + ") << '\\n';\n";
        }
        if (match(Kind::KwIf)) return parse_if();
        if (match(Kind::KwRepeat)) {
            const auto count = render(collect_until(Kind::LBrace));
            const int id = repeat_id_++;
            const std::string variable = "__cdiv_repeat_" + std::to_string(id);
            return "for (long long " + variable + " = 0; " + variable + " < (" + count + "); ++" +
                   variable + ") " + parse_block();
        }
        if (match(Kind::KwWhile)) {
            const auto condition = render(collect_until(Kind::LBrace));
            return "while (" + condition + ") " + parse_block();
        }
        if (match(Kind::KwReturn)) {
            if (function_depth_ == 0)
                fail(tokens_.at(current_ - 1), "'return' is only valid inside a function");
            if (match(Kind::Semicolon)) return "return;\n";
            const auto expression = render(collect_until(Kind::Semicolon));
            consume(Kind::Semicolon, "expected ';' after return");
            return "    return " + expression + ";\n";
        }
        if (match(Kind::LBrace)) {
            --current_;
            return parse_block();
        }
        if (match(Kind::KwImport)) {
            parse_import();
            return {};
        }

        if (check(Kind::Identifier) && current_ + 1 < tokens_.size() &&
            (tokens_[current_ + 1].kind == Kind::Equal || tokens_[current_ + 1].kind == Kind::Colon)) {
            const Token name = advance();
            std::string declared_type;
            bool explicit_type = false;
            if (match(Kind::Colon)) {
                explicit_type = true;
                const Token& type = consume(Kind::Identifier, "expected a type after ':'");
                declared_type = cpp_type(type);
            }
            consume(Kind::Equal, "expected '=' in assignment");
            const auto expression = render(collect_until(Kind::Semicolon));
            consume(Kind::Semicolon, "expected ';' after assignment");
            const bool already_declared = is_declared(name.lexeme);
            if (!already_declared) {
                declare_name(name.lexeme);
                return "    " + (explicit_type ? declared_type : "auto") + " " + name.lexeme +
                       " = " + expression + ";\n";
            }
            return "    " + name.lexeme + " = " + expression + ";\n";
        }

        const auto expression = render(collect_until(Kind::Semicolon));
        consume(Kind::Semicolon, "expected ';' after expression");
        return "    " + expression + ";\n";
    }
};

inline std::string shell_quote(const std::string& value) {
#ifdef _WIN32
    std::string result = "\"";
    for (char c : value) {
        if (c == '"') result += "\\\"";
        else result += c;
    }
    result += '"';
    return result;
#else
    std::string result = "'";
    for (char c : value) {
        if (c == '\'') result += "'\\''";
        else result += c;
    }
    result += "'";
    return result;
#endif
}

inline std::filesystem::path unique_temp_path(const std::string& suffix) {
    const auto stamp = std::chrono::steady_clock::now().time_since_epoch().count();
    return std::filesystem::temp_directory_path() / ("cdiv-" + std::to_string(stamp) + suffix);
}

inline int compile_cpp_file(const std::filesystem::path& cpp_file,
                            const std::filesystem::path& output_file) {
    const char* configured = std::getenv("CXX");
    const std::string compiler = (configured && *configured) ? configured : "c++";
    std::error_code ec;
    if (!output_file.parent_path().empty())
        std::filesystem::create_directories(output_file.parent_path(), ec);

    std::string command;
#ifdef _WIN32
    const bool msvc = compiler == "cl" || compiler == "cl.exe";
    if (msvc) {
        command = compiler + " /nologo /std:c++20 /EHsc /O2 " + shell_quote(cpp_file.string()) +
                  " /Fe:" + shell_quote(output_file.string());
    } else {
        command = compiler + " -std=c++20 -O2 " + shell_quote(cpp_file.string()) +
                  " -o " + shell_quote(output_file.string());
    }
#else
    command = compiler + " -std=c++20 -O2 " + shell_quote(cpp_file.string()) +
              " -o " + shell_quote(output_file.string());
#endif
    return std::system(command.c_str());
}

inline int build_native_program(const std::string& cpp_source,
                                const std::filesystem::path& output_file) {
    const auto cpp_file = unique_temp_path(".cpp");
    {
        std::ofstream output(cpp_file, std::ios::binary);
        if (!output) {
            std::cerr << "error: cannot create temporary C++ source file\n";
            return 1;
        }
        output << cpp_source;
    }
    const int result = compile_cpp_file(cpp_file, output_file);
    std::error_code ignored;
    std::filesystem::remove(cpp_file, ignored);
    if (result != 0) {
        std::cerr << "error: native compilation failed. Install a C++20 compiler or set CXX.\n";
        return 1;
    }
    return 0;
}

inline int run_native_program(const std::filesystem::path& executable) {
    return std::system(shell_quote(executable.string()).c_str()) == 0 ? 0 : 1;
}

